/* Route picker for a513.html.
   Reads window.A513 (generated by scripts/build_a513.py) and re-renders the cost table.
   Without JavaScript the server-rendered M01 table is still valid HTML — nothing here invents a number. */
(function () {
  "use strict";
  var sel = document.getElementById("method");
  var body = document.getElementById("mbody");
  var cap = document.getElementById("mcap");
  if (!sel || !body || !window.A513) return;

  function money(v) {
    if (v === "" || v === null || v === undefined) return '<span class="blank">not verified</span>';
    var n = Number(v);
    if (!isFinite(n)) return '<span class="blank">not verified</span>';
    return "$" + n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }

  function render(id) {
    var rows = window.A513.methods[id] || [];
    var out = "";
    rows.forEach(function (r) {
      out += '<tr><th scope="row">' + Number(r[0]).toLocaleString("en-US") + "</th>" +
        '<td data-l="Cost">' + money(r[1]) + "</td>" +
        '<td data-l="All-in %">' + (r[2] ? r[2] + "%" : "—") + "</td>" +
        '<td data-l="Note">' + (r[3] || (r[4] === "UNVERIFIED" ? "no official price found — flagged" : "")) + "</td></tr>";
    });
    body.innerHTML = out;
    if (cap) {
      cap.textContent = (window.A513.labels[id] || id) +
        " — blank means no official price found (flagged), never zero.";
    }
  }

  sel.addEventListener("change", function () { render(sel.value); });
  render(sel.value);
})();
