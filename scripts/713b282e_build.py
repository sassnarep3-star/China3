#!/usr/bin/env python3
"""713b282e session build script.

Generates the user-requested CNY->USD answer set from the verified data that
earlier sessions read at official sources:

  data/e347_costs.csv     11 lawful routes x 40 amounts ($10,000..$400,000)
  data/e347_methods.csv   L01-L11 lawful, P01-P06 prohibited, with pros/cons
  data/e347_steps.csv     numbered step-by-step playbook per route
  data/e347_flags.csv     U01-U19 open items (blank-unverified rule)
  data/e347_sources.csv   S01-S35 official pages, read 2026-11-10 / 2026-11-11
  data/cost_inputs.csv    CI01-CI32 model inputs

Nothing is fetched live (this sandbox reaches GitHub/npm/PyPI only). Every
figure is re-derived from the recorded sources and each row carries those
source URLs. Anything that cannot be confirmed is left blank and flagged.

Outputs (713b282e-* namespace only - no file claimed by another session is
touched):
  713b282e-index.html          landing page, most important info first
  713b282e-executive-summary.html
  713b282e-questions-answers.html
  713b282e-methods.html
  713b282e-costs.html
  713b282e-steps.html
  713b282e-tax.html
  713b282e-flagged.html
  713b282e-sources.html
  713b282e-style.css           (hand-written, mobile first)
  data/713b282e_cost_matrix.csv (consolidated 440-row matrix)
"""
import csv, html
from decimal import Decimal as D
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT


def money(x):
    if x is None or str(x).strip() == "":
        return ""
    return f"${D(x):,.2f}"


def esc(s):
    return html.escape(str(s), quote=True)


def read_csv(name):
    with open(DATA / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


# --------------------------------------------------------------------------- load
METHODS = {}
for r in read_csv("e347_methods.csv"):
    METHODS[r["id"]] = r

COSTS = {}
for r in read_csv("e347_costs.csv"):
    COSTS.setdefault(r["method_id"], {})[r["amount_usd"]] = r

STEPS = {}
for r in read_csv("e347_steps.csv"):
    STEPS.setdefault(r["method_id"], []).append(r)

FLAGS = {r["id"]: r for r in read_csv("e347_flags.csv")}
SOURCES = read_csv("e347_sources.csv")

AMOUNTS = [str(a) for a in range(10000, 400001, 10000)]
KEY_AMOUNTS = ["10000", "50000", "100000", "200000", "400000"]

LAWFUL = [m for m in METHODS.values() if m["status"].startswith("Lawful")]
PROHIBITED = [m for m in METHODS.values() if m["status"] == "Prohibited"]


def src_links(r):
    ids = [i for i in (r.get("source_ids") or "").split("|") if i]
    urls = (r.get("source_urls") or "").split(" ")
    return " ".join(
        f'<a href="{esc(u)}" rel="noopener">{esc(i)}</a>' for i, u in zip(ids, urls)
    )


def flag_badge(fid):
    f = FLAGS.get(fid, {})
    sev = f.get("severity", "medium")
    cls = {"high": "bad", "medium": "warn", "low": "ok"}.get(sev, "warn")
    return f'<span class="pill {cls}">{esc(fid)}</span>'


