# --------------------------------------------------------------------------- cost matrix
MATRIX = []
for mid in [m["id"] for m in LAWFUL]:
    for amt in AMOUNTS:
        r = COSTS.get(mid, {}).get(amt)
        if not r:
            continue
        spread = D(r["spread_usd"]) if r.get("spread_usd") else D(0)
        fee = D(r["fee_usd"]) if r.get("fee_usd") else D(0)
        tax = D(r["tax_usd"]) if r.get("tax_usd") else D(0)
        known = D(r["known_cost_usd"]) if r.get("known_cost_usd") else spread + fee + tax
        MATRIX.append({
            "method_id": mid, "route": METHODS[mid]["route"],
            "amount": int(amt),
            "spread_usd": spread, "fee_usd": fee, "tax_usd": tax,
            "known_cost_usd": known,
            "known_cost_pct": D(r["known_cost_pct"]) if r.get("known_cost_pct") else None,
            "rmb_debited": D(r["rmb_debited"]) if r.get("rmb_debited") else None,
            "calendar_years": r.get("calendar_years", ""),
            "flags": [x for x in (r.get("not_included_flags") or "").split("|") if x],
            "source_ids": [i for i in (r.get("source_ids") or "").split("|") if i],
            "source_urls": (r.get("source_urls") or "").split(" "),
        })
with open(DATA / "713b282e_cost_matrix.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["method_id", "route", "amount_usd", "spread_usd", "fee_usd", "tax_usd",
                "known_cost_usd", "known_cost_pct", "rmb_debited", "calendar_years",
                "flags", "source_ids", "source_urls"])
    for row in MATRIX:
        w.writerow([row["method_id"], row["route"], row["amount"],
                    row["spread_usd"], row["fee_usd"], row["tax_usd"],
                    row["known_cost_usd"], row["known_cost_pct"], row["rmb_debited"],
                    row["calendar_years"], " ".join(row["flags"]),
                    " ".join(row["source_ids"]), " ".join(row["source_urls"])])
print(f"matrix rows: {len(MATRIX)}")


def cost_row_for(mid, amt):
    return COSTS.get(mid, {}).get(str(amt))


def net_received(amt, known):
    if known in (None, ""):
        return ""
    return D(amt) - D(known)


