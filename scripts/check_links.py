#!/usr/bin/env python3
"""Link integrity checks for the built site.

Checks (offline, deterministic):
  1. every internal href/src in docs/*.html resolves to a file that exists
  2. every internal #anchor resolves to an id that the target page will contain
     (ids generated by app.js from data are resolved from the data files)
  3. every source id referenced as sources.html#Sxx exists in the register
  4. every external URL in the register is well formed, https, and unique
  5. the generated bundle in docs/assets/data.js matches the data files

With --fetch it additionally performs HTTP HEAD/GET checks on external URLs
(needs outbound network; skipped by default because the build sandbox is
network-restricted).

Exit code 0 = clean, 1 = problems.
"""
from __future__ import annotations

import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
DATA = ROOT / "data"

HREF = re.compile(r'(?:href|src)="([^"]+)"')


def load(name: str) -> dict:
    with (DATA / name).open(encoding="utf-8") as fh:
        return json.load(fh)


def generated_ids() -> dict[str, set[str]]:
    """Anchors that app.js will create on each page."""
    ids: dict[str, set[str]] = {}
    ids["sources.html"] = {s["id"] for s in load("sources.json")["sources"]}
    ids["channels.html"] = {"d-" + c["id"] for c in load("channels.json")["channels"]}
    ids["flagged.html"] = set()
    ids["taxes.html"] = set()
    ids["penalties.html"] = set()
    # every page carries these from the shell
    shell_ids = {"nav", "app"}
    return ids, shell_ids


def main() -> int:
    fetch = "--fetch" in sys.argv
    errs: list[str] = []
    warns: list[str] = []

    pages = sorted(DOCS.glob("*.html"))
    if not pages:
        print("No pages found in docs/. Run scripts/build_site.py first.")
        return 1

    gen, shell_ids = generated_ids()
    static_ids: dict[str, set[str]] = {}

    for page in pages:
        html = page.read_text(encoding="utf-8")
        ids = set(re.findall(r'\bid="([^"]+)"', html)) | shell_ids
        static_ids[page.name] = ids

    for page in pages:
        html = page.read_text(encoding="utf-8")
        for target in HREF.findall(html):
            if target.startswith(("data:", "mailto:", "javascript:", "#")):
                continue
            if target.startswith(("http://", "https://")):
                continue  # external links are the register's job
            path_part, _, anchor = target.partition("#")
            if not path_part:
                continue
            dest = (DOCS / path_part).resolve()
            if not dest.exists():
                errs.append(f"{page.name}: broken internal link -> {target}")
                continue
            if anchor:
                ok = (anchor in static_ids.get(dest.name, set())) or (anchor in gen.get(dest.name, set()))
                if not ok:
                    errs.append(f"{page.name}: broken anchor -> {target}")

    # ---- source register hygiene ----
    reg = load("sources.json")["sources"]
    seen: dict[str, str] = {}
    for s in reg:
        url = s.get("url", "")
        parsed = urllib.parse.urlparse(url)
        if parsed.scheme not in {"http", "https"}:
            errs.append(f"{s['id']}: url is not http(s): {url!r}")
        if not parsed.netloc:
            errs.append(f"{s['id']}: url has no host: {url!r}")
        if " " in url:
            errs.append(f"{s['id']}: url contains a space")
        if url in seen:
            errs.append(f"{s['id']}: duplicate url (also {seen[url]})")
        else:
            seen[url] = s["id"]

    # ---- source chips on pages must resolve ----
    known = {s["id"] for s in reg}
    for page in pages:
        html = page.read_text(encoding="utf-8")
        for anchor in re.findall(r"sources\.html#(I[A-Z]\d+|S\d+)", html):
            if anchor.startswith("S") and anchor not in known:
                errs.append(f"{page.name}: cites unknown source {anchor}")

    # ---- bundle freshness ----
    bundle = DOCS / "assets" / "data.js"
    if not bundle.exists():
        errs.append("docs/assets/data.js missing — run scripts/build_site.py")
    else:
        text = bundle.read_text(encoding="utf-8")
        for name, key in (("sources.json", "sources"), ("channels.json", "channels"),
                          ("taxes.json", "taxes"), ("penalties.json", "penalties"),
                          ("flagged.json", "flagged")):
            blob = json.dumps(load(name), ensure_ascii=False, separators=(",", ":"))
            if blob not in text:
                errs.append(f"docs/assets/data.js is stale for {name} — rebuild")

    # ---- assets exist ----
    for asset in ("assets/styles.css", "assets/app.js"):
        if not (DOCS / asset).exists():
            errs.append(f"missing asset: docs/{asset}")

    # ---- external check (optional) ----
    if fetch:
        for s in reg:
            url = s["url"]
            try:
                req = urllib.request.Request(url, method="GET", headers={
                    "User-Agent": "Mozilla/5.0 (compatible; China3-link-check)"
                })
                with urllib.request.urlopen(req, timeout=25) as resp:
                    if resp.status >= 400:
                        errs.append(f"{s['id']}: HTTP {resp.status} for {url}")
            except Exception as exc:  # noqa: BLE001
                errs.append(f"{s['id']}: fetch failed ({exc.__class__.__name__}) for {url}")
    else:
        warns.append(f"external HTTP checks skipped for {len(reg)} URLs (offline build); "
                     "run with --fetch on a networked machine")

    for w in warns:
        print(f"NOTE  {w}")
    for e in errs:
        print(f"ERROR {e}")

    if errs:
        print(f"\n{len(errs)} problem(s).")
        return 1
    print(f"OK — {len(pages)} pages, {len(reg)} external URLs, all internal links and anchors resolve.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
