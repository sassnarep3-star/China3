def write() -> None:
    data = ROOT / "data"
    with (data / "f52c_sources.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["id", "issuer", "title", "url", "read_on", "verbatim", "what_it_settles"])
        for sid, issuer, title, url, quote, settles in SOURCES:
            w.writerow([sid, issuer, title, url, READ_ON, quote, settles])

    with (data / "f52c_questions.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["id", "section", "question", "status", "answer", "source_ids",
                    "how_to_settle", "flag"])
        for row in QUESTIONS:
            w.writerow(row)

    with (data / "f52c_flags.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["id", "severity", "item", "why", "what_would_settle_it", "source_ids"])
        for row in FLAGS:
            w.writerow(row)


if __name__ == "__main__":
    write()
    print(f"{len(SOURCES)} sources, {len(QUESTIONS)} questions, {len(FLAGS)} flags -> data/f52c_*.csv")
