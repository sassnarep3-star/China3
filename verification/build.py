def vbadge(v, label=None):
    return f'<span class="v v-{v.replace(" ","-")}">{e(label or v.replace("-"," ").capitalize())}</span>'
def ev_cell(ids):
    out = []
    for i in ids:
        s, q = Q[i]
        link = s.get("resolved_url") or s["url"]
        tier = "Tier 1" if s["tier"] == 1 else "Tier 2 (not law)"
        out.append(f'<div><a href="{e(s["url"])}" target="_blank" rel="noopener">{e(s["short"])}</a> <span class="small">· {e(q["loc"])} · {tier}</span>')
        if q.get("orig") or q.get("en"):
            lab = "Quoted text" if q["verbatim"] else "Summary of text read (paraphrase)"
            d = ""
            if q.get("orig"): d += f'<div class="orig" lang="zh">{e(q["orig"])}</div>'
            if q.get("en"):
                pre = "" if q["verbatim"] and not q.get("orig") else ("Working translation: " if q.get("orig") else "")
                d += f'<div class="tr">{pre}{e(q["en"])}</div>'
            if q.get("note"): d += f'<div class="small">{e(q["note"])}</div>'
            out[-1] += f'<details><summary>{lab} [{e(i)}]</summary>{d}</details>'
        out[-1] += "</div>"
    return "".join(out)

# ---------------------------------------------------------------- coverage scan
def external_urls():
    found = defaultdict(set)
    for f in glob.glob(os.path.join(ROOT, "**", "*"), recursive=True):
        rel = os.path.relpath(f, ROOT)
        if not f.endswith((".html", ".md", ".json", ".csv")) or rel.startswith((".git", "node_modules", "verification" + os.sep)) or rel in ("docs/assets/data.js", "verification.html", "primary-rules.html"):
            continue
        t = open(f, encoding="utf-8", errors="ignore").read()
        for m in re.finditer(r'https?://[^\s"\'<>)\]`}]+', t):
            u = m.group(0).rstrip(".,;:")
            if any(x in u for x in ("sassnarep3-star", "github.com", "localhost", "schema.org", "w3.org")): continue
            found[u].add(rel)
    return found
def norm(u): return re.sub(r"^https?://(www\.)?", "", u).rstrip("/")
