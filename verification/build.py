#!/usr/bin/env python3
"""Render verification.html, primary-rules.html and verification/report.md from
verification/ledger.json and verification/claims.json. Standard library only.

    python3 verification/build.py            # validate + write
    python3 verification/build.py --check    # validate; exit 1 if outputs are stale

Validation (the build aborts on any failure):
  * every evidence id resolves to a quote in the ledger;
  * every claim / rule / gap / figure row carries at least one Tier-1 source link;
  * verdicts come from the declared vocabulary;
  * verbatim=false quotes are rendered with a 'paraphrase' label.
"""
import glob, html, json, os, re, sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = os.path.join(ROOT, "verification")
led = json.load(open(os.path.join(V, "ledger.json"), encoding="utf-8"))
cl = json.load(open(os.path.join(V, "claims.json"), encoding="utf-8"))
SRC = {s["id"]: s for s in led["sources"]}
Q = {}
for s in led["sources"]:
    for q in s["quotes"]:
        Q[q["id"]] = (s, q)
e = lambda t: html.escape(str(t), quote=True)

def fail(msg):
    print("BUILD FAILED:", msg); sys.exit(2)

# ---------------------------------------------------------------- validation
VERD = cl["meta"]["verdicts"]
def need_tier1(rowid, ev, bank_fact=False):
    """Every row needs a Tier-1 source. Exception: a bank-specific commercial fact (a fee) may rest on that
    bank's own published fee table (Tier 2, kind 'bank fee table') - flagged bank_fact in claims.json."""
    if not ev: fail(f"{rowid}: no evidence")
    for x in ev:
        if x not in Q: fail(f"{rowid}: unresolved evidence id {x}")
    if bank_fact:
        if not any(Q[x][0]["kind"] == "bank fee table" for x in ev):
            fail(f"{rowid}: bank_fact row needs a bank fee table source")
    elif not any(Q[x][0]["tier"] == 1 for x in ev):
        fail(f"{rowid}: no Tier-1 source among {ev}")
for c in cl["claims"]:
    if c["verdict"] not in VERD: fail(f"{c['id']}: bad verdict {c['verdict']}")
    need_tier1(c["id"], c["evidence"], c.get("bank_fact", False))
for k in ("gaps", "rules", "usfacts"):
    for r in cl[k]: need_tier1(r["id"], r["evidence"], r.get("bank_fact", False))
for b in cl["blank"]:
    if not b.get("why") or not b.get("check"): fail(f"{b['id']}: blank row needs why/check")

# ---------------------------------------------------------------- shared html
