# ---------------------------------------------------------------- report.md
def build_report():
    cnt = Counter(c["verdict"] for c in cl["claims"])
    L = ["# Verification report (F83-A)", "", f"Retrieved {led['meta']['retrieved']}; audited tree {cl['meta']['audited_tree']}. Generated by `verification/build.py` - do not edit by hand.", "",
         "| Verdict | Count |", "|---|---|"] + [f"| {k} | {cnt[k]} |" for k in ("contradicted", "superseded", "defect", "partly", "not-checked", "confirmed")] + ["",
         "## Claims that need action", ""]
    for c in cl["claims"]:
        if c["verdict"] in ("contradicted", "superseded", "defect", "partly", "not-checked"):
            urls = ", ".join(sorted({Q[x][0]["url"] for x in c["evidence"] if Q[x][0]["tier"] == 1}))
            L += [f"- **{c['id']} ({c['verdict']})** {c['topic']}: {c['finding']} Evidence: {urls}"]
    L += ["", "## Gaps still blank", ""] + [f"- **{b['id']}** {b['item']} - {b['why']}" for b in cl["blank"]]
    return "\n".join(L) + "\n"

